#!/usr/bin/env python3
"""Write .dbt/profiles.yml from DATABASE_URL.

dbt wants a profile with host/port/user/dbname spelled out; the rest of this repo
passes a single DATABASE_URL, because that is what every other slot and the whole
harness use. Rather than ask whoever runs this slot to keep two representations of
one connection in sync, the profile is generated from the URL on every invocation.

Written to ./.dbt/ and git-ignored, so a real password in DATABASE_URL never ends
up in a committed file.
"""

from __future__ import annotations

import os
import pathlib
import sys
import urllib.parse

SLOT = pathlib.Path(__file__).resolve().parents[1]
OUT = SLOT / ".dbt" / "profiles.yml"


def main() -> None:
    url = os.environ.get("DATABASE_URL")
    if not url:
        sys.exit("DATABASE_URL is not set — see .env.example")

    parts = urllib.parse.urlparse(url)
    if parts.scheme not in ("postgres", "postgresql"):
        sys.exit(f"DATABASE_URL must be a postgres:// URL, got {parts.scheme!r}")

    dbname = parts.path.lstrip("/")
    if not dbname:
        sys.exit("DATABASE_URL has no database name")

    def esc(value: str) -> str:
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# GENERATED by tools/profile.py from DATABASE_URL. Do not commit.\n"
        "ticketforge:\n"
        "  target: dev\n"
        "  outputs:\n"
        "    dev:\n"
        "      type: postgres\n"
        f"      host: {esc(urllib.parse.unquote(parts.hostname or '127.0.0.1'))}\n"
        f"      port: {parts.port or 5432}\n"
        f"      user: {esc(urllib.parse.unquote(parts.username or os.environ.get('USER', 'postgres')))}\n"
        f"      password: {esc(urllib.parse.unquote(parts.password or ''))}\n"
        f"      dbname: {esc(urllib.parse.unquote(dbname))}\n"
        "      schema: public\n"
        "      threads: 4\n"
        "      connect_timeout: 10\n"
    )
    print(f"wrote {OUT.relative_to(SLOT)} for database {dbname}")


if __name__ == "__main__":
    main()
